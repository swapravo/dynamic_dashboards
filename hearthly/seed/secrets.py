"""Write docs/DEMO_SECRETS.md (presenter only) from measured story numbers."""

from __future__ import annotations

import sqlite3
from pathlib import Path

from .. import config
from .stories import measure
from .timeline import Timeline


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def _inr(x: float) -> str:
    return f"₹{x:,.0f}"


def render(n: dict, tl: Timeline) -> str:
    kettle_mult = n["kettle_b17_refund_rate"] / n["baseline_item_refund_rate"]
    late_mult = n["swiftship_ne_late_pct"] / n["baseline_late_pct"]
    return f"""# DEMO SECRETS — presenter only

> Do **not** show this file on the projector. Nothing here is exposed through the MCP server,
> its tool descriptions, the schema resource or the web app. Claude has to find these by querying.

Generated by `python -m hearthly.seed --reset` with seed 42. Dates are relative to the
day you seeded: **as of {n['as_of']}**, data covers **{n['start']} → {n['end']}** (yesterday).
Re-seeding on a different day shifts every date below; the numbers stay roughly the same.

Volumes: {n['n_orders']:,} orders · {n['n_customers']:,} customers · {n['n_products']} products ·
{n['n_order_items']:,} order items · {n['n_refunds']:,} refund requests · {n['n_support_tickets']:,} tickets ·
{n['n_agent_runs']:,} RefundDesk agent runs.

---

## 1. Bad kettle batch (KT-B17)
- Product **AirBrew Electric Kettle** (SKU `KA-KETTLE`), batch **KT-B17**, dispatched
  **{n['kettle_b17_start']} → {n['kettle_b17_end']}** (15 days, starting ~60 days ago). {n['kettle_b17_items']:,} items.
- Item refund-request rate: **{_pct(n['kettle_b17_refund_rate'])}** vs **{_pct(n['baseline_item_refund_rate'])}**
  baseline (all other items) → **{kettle_mult:.1f}×**. Other kettle batches: {_pct(n['kettle_other_refund_rate'])}.
- Reason mix: **{_pct(n['kettle_b17_defective_share'])} "defective"** vs {_pct(n['baseline_defective_share'])} elsewhere.
- How Claude finds it: refunds by product → kettle stands out recently → refunds by `order_items.batch_code`.

## 2. SwiftShip delays to the Northeast
- From **{n['courier_delay_start']}** (~40 days ago), courier **SwiftShip** shipping to the 8 Northeast states
  (Assam, Meghalaya, Tripura, Manipur, Arunachal Pradesh, Nagaland, Mizoram, Sikkim).
- Late deliveries (delivered date > promised_date): **{_pct(n['swiftship_ne_late_pct'])}**
  ({n['swiftship_ne_shipments']:,} delivered shipments) vs **{_pct(n['baseline_late_pct'])}** for everything else ({late_mult:.1f}×).
  Other couriers into the Northeast over the same period: {_pct(n['other_couriers_ne_recent_late_pct'])}.
- "where_is_my_order" tickets from Northeast customers: **{n['ne_wismo_per_day_recent']:.1f}/day** since then
  vs {n['ne_wismo_per_day_prior']:.1f}/day in the 90 days before.
- How Claude finds it: on-time % by week → dip → by courier × region/destination_state.

## 3. Weekend Flash Sale trade-off
- Campaign **"Weekend Flash Sale"** runs **{n['flash_start']} → {n['flash_end']}**, Saturdays and Sundays only
  (orders on those days carry its `campaign_id` and a 10–13% discount).
- Average gross revenue per flash weekend day: **{_inr(n['flash_weekend_avg_revenue'])}** vs
  **{_inr(n['nearby_weekend_avg_revenue'])}** on nearby normal weekends → **+{_pct(n['flash_revenue_lift'])}**.
  (All non-festive normal weekends: {_inr(n['normal_weekend_avg_revenue'])}.)
- Gross margin (gross − discount − COGS) / gross: **{_pct(n['flash_weekend_margin'])}** on flash weekends vs
  **{_pct(n['nearby_weekend_margin'])}** nearby → **{n['flash_margin_delta_pts']:+.1f} pts**.
- Repeat purchase (customers whose first order was in the window, share with 2+ orders ever):
  **{_pct(n['flash_repeat_rate'])}** for flash-sale first orders ({n['flash_new_customers']:,} customers) vs
  **{_pct(n['other_repeat_rate'])}** for other first orders in the same window.

## 4. Seasonality
- Average daily gross revenue: festive Oct–Nov **{_inr(n['festive_avg_daily_revenue'])}**, January
  **{_inr(n['january_avg_daily_revenue'])}**, other months **{_inr(n['other_avg_daily_revenue'])}**.
- Weekend days {_inr(n['weekend_avg_daily_revenue'])} vs weekdays {_inr(n['weekday_avg_daily_revenue'])}.
  Diwali peak is late Oct – mid Nov. Gentle growth trend over the 18 months.

## 5. RefundDesk AI agent drift
- `prompt_version` **v3 → v4 on {n['prompt_v4_start']}** (~21 days ago).
  `audit_correct`: **{_pct(n['acc_v3'])}** (v3, last 60 days, {n['runs_v3']} runs) → **{_pct(n['acc_v4'])}** (v4, {n['runs_v4']} runs).
- Concentrated in **boundary cases** — refund requested 27–33 days after delivery, around the
  30-day return window: {_pct(n['acc_v3_boundary'])} → **{_pct(n['acc_v4_boundary'])}**
  ({n['runs_v4_boundary']} v4 runs). Non-boundary: {_pct(n['acc_v3_normal'])} → {_pct(n['acc_v4_normal'])}.
  (Boundary = `julianday(date(refunds.requested_at)) - julianday(date(shipments.delivered_at))` between 27 and 33.)
- **Model swap on {n['model_swap']}** (~10 days ago): `hx-pro-2026-03` → `hx-lite-2026-10`
  (agent_version 1.3.0 → 1.3.1). Avg cost per run **${n['cost_pro']:.4f} → ${n['cost_lite']:.4f}**, avg latency
  **{n['latency_pro']:,.0f} ms → {n['latency_lite']:,.0f} ms**.
- Earlier history: v1 at launch (~270 days ago), v2 ~200 days ago, v3 ~120 days ago, each slightly better.

## 6. Data-quality realism
- **{_pct(n['null_state_pct'])}** of shipments ({n['null_state_orders']:,}) have `destination_state` NULL.
- **{n['late_arriving_refunds']}** refunds were requested more than 90 days after the order date.
- **{n['pending_refunds']}** refunds are still `pending` (resolved_at NULL).
- `refunds.amount` is the amount actually refunded (0 when denied; the requested amount while pending).

---

### Quick verification queries
```sql
-- 1. kettle batches
SELECT oi.batch_code, COUNT(DISTINCT oi.id) items, COUNT(DISTINCT r.order_item_id) refunded
FROM order_items oi LEFT JOIN refunds r ON r.order_item_id = oi.id
WHERE oi.batch_code LIKE 'KT-%' GROUP BY 1 ORDER BY 1;
-- 2. late % by courier for the Northeast, last 40 days
SELECT courier, AVG(date(delivered_at) > promised_date) late_pct, COUNT(*)
FROM shipments WHERE delivered_at IS NOT NULL AND dispatched_at >= date('now','-40 day')
  AND destination_state IN ('Assam','Meghalaya','Tripura','Manipur','Arunachal Pradesh','Nagaland','Mizoram','Sikkim')
GROUP BY 1;
-- 5. agent accuracy by prompt version
SELECT prompt_version, model, AVG(audit_correct), AVG(cost_usd), AVG(latency_ms), COUNT(*)
FROM agent_runs GROUP BY 1, 2 ORDER BY MIN(run_at);
```
"""


def write_secrets(db_path: Path, tl: Timeline, out: Path | None = None) -> Path:
    out = out or (config.PROJECT_ROOT / "docs" / "DEMO_SECRETS.md")
    conn = sqlite3.connect(db_path)
    try:
        numbers = measure(conn, tl)
    finally:
        conn.close()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(numbers.values, tl), encoding="utf-8")
    return out
